"""
Benchmark Runner — Runs evaluation on synthetic test data and produces reports.

Usage:
    python -m src.evaluation.benchmark --data-dir data/synthetic --output evaluation_report.json
"""

import os
import json
import time
import argparse
import logging
from typing import Any, Dict, List, Optional

import numpy as np
import torch

from src.evaluation.evaluator import DASIEvaluator

logger = logging.getLogger(__name__)


class BenchmarkRunner:
    """Runs the DASI system against a test dataset and evaluates performance.
    
    Supports:
      - Loading synthetic datasets generated by dataset_generator.py
      - Running each sample through the full pipeline
      - Collecting comprehensive metrics via DASIEvaluator
      - Generating text and JSON reports
    """
    
    def __init__(self, orchestrator=None):
        self.orchestrator = orchestrator
        self.evaluator = DASIEvaluator(name="DASI Benchmark")
    
    def load_test_data(self, data_dir: str) -> List[Dict]:
        """Load test data from the synthetic dataset directory.
        
        Args:
            data_dir: Directory containing synthetic dataset JSON files.
            
        Returns:
            List of test samples with labels.
        """
        test_samples = []
        
        # Load conversations
        conversations_path = os.path.join(data_dir, "conversations.json")
        if os.path.exists(conversations_path):
            with open(conversations_path, "r", encoding="utf-8") as f:
                conversations = json.load(f)
            
            for conv in conversations:
                sample = {
                    "messages": conv.get("messages", []),
                    "is_scam": conv.get("is_scam", False),
                    "scam_phase": conv.get("scam_phase"),
                    "campaign_label": conv.get("campaign_id"),
                    "language": conv.get("language", "en"),
                    "region": conv.get("region"),
                    "latitude": conv.get("latitude"),
                    "longitude": conv.get("longitude"),
                }
                test_samples.append(sample)
        
        # Load scenarios (richer format)
        scenarios_dir = os.path.join(data_dir, "scenarios")
        if os.path.isdir(scenarios_dir):
            for fname in sorted(os.listdir(scenarios_dir)):
                if fname.endswith(".json"):
                    fpath = os.path.join(scenarios_dir, fname)
                    with open(fpath, "r", encoding="utf-8") as f:
                        scenario = json.load(f)
                    test_samples.append(scenario)
        
        logger.info(f"Loaded {len(test_samples)} test samples from {data_dir}")
        return test_samples
    
    def run(
        self,
        test_data: List[Dict],
        threshold: float = 0.5,
        max_samples: Optional[int] = None,
    ) -> Dict[str, Any]:
        """Run the benchmark on test data.
        
        Args:
            test_data: List of test samples.
            threshold: Classification threshold.
            max_samples: Optional limit on number of samples.
            
        Returns:
            Evaluation metrics dictionary.
        """
        if max_samples:
            test_data = test_data[:max_samples]
        
        logger.info(f"Running benchmark on {len(test_data)} samples...")
        start_time = time.time()
        
        for i, sample in enumerate(test_data):
            try:
                if self.orchestrator:
                    # Run through full pipeline
                    result = self.orchestrator.process(sample)
                    
                    self.evaluator.record(
                        prediction=result.threat_assessment.threat_score,
                        ground_truth=1 if sample.get("is_scam", False) else 0,
                        threat_level=result.threat_assessment.threat_level,
                        phase=sample.get("scam_phase"),
                        campaign_pred=result.campaign_id,
                        campaign_true=sample.get("campaign_label"),
                        signal_contributions=result.threat_assessment.signal_contributions,
                        processing_time_ms=result.processing_time_ms,
                        escalation_speed=result.threat_assessment.escalation_speed,
                    )
                else:
                    # Simulated evaluation (no orchestrator — useful for testing evaluator)
                    is_scam = sample.get("is_scam", False)
                    # Simulate a prediction with some noise
                    base_score = 0.8 if is_scam else 0.2
                    noise = np.random.normal(0, 0.15)
                    pred_score = np.clip(base_score + noise, 0, 1)
                    
                    self.evaluator.record(
                        prediction=pred_score,
                        ground_truth=1 if is_scam else 0,
                        phase=sample.get("scam_phase"),
                        campaign_pred=np.random.randint(0, 10),
                        campaign_true=sample.get("campaign_label"),
                        signal_contributions={
                            "conversation_semantics": np.random.uniform(0.1, 0.4),
                            "temporal_sequence": np.random.uniform(0.1, 0.3),
                            "voice_analysis": np.random.uniform(0.05, 0.2),
                            "network_graph": np.random.uniform(0.1, 0.3),
                            "geo_temporal": np.random.uniform(0.05, 0.15),
                        },
                        processing_time_ms=np.random.uniform(10, 100),
                    )
                
                if (i + 1) % 50 == 0:
                    logger.info(f"  Processed {i + 1}/{len(test_data)} samples...")
                    
            except Exception as e:
                logger.warning(f"Sample {i} failed: {e}")
        
        total_time = time.time() - start_time
        logger.info(f"Benchmark complete in {total_time:.2f}s")
        
        # Compute and return metrics
        metrics = self.evaluator.compute_metrics(threshold)
        metrics["benchmark_time_seconds"] = round(total_time, 2)
        
        return metrics
    
    def generate_report(self, threshold: float = 0.5) -> str:
        """Generate human-readable report."""
        return self.evaluator.generate_report(threshold)
    
    def save_report(self, output_path: str, threshold: float = 0.5):
        """Save evaluation report to file."""
        self.evaluator.save_report(output_path, threshold)


def main():
    """CLI entry point for benchmarking."""
    parser = argparse.ArgumentParser(
        description="Run DASI benchmark evaluation"
    )
    parser.add_argument(
        "--data-dir", type=str, default="data/synthetic",
        help="Directory containing test data"
    )
    parser.add_argument(
        "--output", type=str, default="evaluation_report.json",
        help="Output path for evaluation report"
    )
    parser.add_argument(
        "--threshold", type=float, default=0.5,
        help="Classification threshold"
    )
    parser.add_argument(
        "--max-samples", type=int, default=None,
        help="Max samples to evaluate"
    )
    parser.add_argument(
        "--simulate", action="store_true",
        help="Run with simulated predictions (no model loading)"
    )
    
    args = parser.parse_args()
    
    logging.basicConfig(level=logging.INFO)
    
    runner = BenchmarkRunner(orchestrator=None if args.simulate else None)
    
    # Load test data
    test_data = runner.load_test_data(args.data_dir)
    
    if not test_data:
        # Generate dummy test data for demonstration
        logger.info("No test data found. Generating demo data...")
        test_data = []
        for i in range(200):
            is_scam = i < 100
            test_data.append({
                "messages": [
                    {"role": "caller", "text": f"Test message {i}", "timestamp_offset": 0}
                ],
                "is_scam": is_scam,
                "scam_phase": (i % 6) + 1 if is_scam else None,
                "campaign_label": f"campaign_{i // 20}" if is_scam else None,
            })
    
    # Run benchmark
    metrics = runner.run(test_data, threshold=args.threshold, max_samples=args.max_samples)
    
    # Print report
    print(runner.generate_report(args.threshold))
    
    # Save report
    runner.save_report(args.output, args.threshold)
    print(f"\nReport saved to: {args.output}")


if __name__ == "__main__":
    main()
